-- Run this in the Supabase SQL editor. Rows are private to their signed-in owner.
create table if not exists public.antenna_designs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  material_label text not null,
  frequency_ghz double precision not null,
  epsilon_r double precision not null,
  loss_tangent double precision not null,
  substrate_mm double precision not null,
  patch_width_mm double precision not null,
  patch_length_mm double precision not null
);

alter table public.antenna_designs enable row level security;
create policy "Users can read their own antenna designs"
  on public.antenna_designs for select to authenticated using (auth.uid() = user_id);
create policy "Users can insert their own antenna designs"
  on public.antenna_designs for insert to authenticated with check (auth.uid() = user_id);
create policy "Users can delete their own antenna designs"
  on public.antenna_designs for delete to authenticated using (auth.uid() = user_id);

